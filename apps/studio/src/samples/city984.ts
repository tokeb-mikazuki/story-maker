// ───────────────────────── 짧은 도우미 ─────────────────────────

function add(v: string, n: NumOrExpr): Command {
  return { do: 'add', var: v, value: n };
}
function set(v: string, n: NumOrExpr): Command {
  return { do: 'set', var: v, value: n };
}
/** 태그: 값이 있으면 문자열 값으로 */
function tag(key: string, value?: string): Command {
  return value === undefined ? { do: 'tag', key } : { do: 'tag', key, value: `'${value}'` };
}
function untag(key: string): Command {
  return { do: 'untag', key };
}
function note(text: string): Command {
  return { do: 'note', text };
}
function rec(text: string, importance = 3): Command {
  return { do: 'record', text, importance };
}
function end(ending: string): Command {
  return { do: 'end', ending };
}
function item(id: string, count = 1): Command {
  return { do: 'item', id, count };
}
function job(j: string): Command[] {
  return [tag('직업', j), set('실적', 0)];
}

