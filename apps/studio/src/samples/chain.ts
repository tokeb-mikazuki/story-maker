function build(): EventDef[] {
  const flat: { id: string; title?: string; text: string }[] = [];
  let n = 0;
  for (const ch of CHAPTERS)
    ch.pages.forEach((page, i) => {
      n += 1;
      flat.push({ id: `p${String(n).padStart(3, '0')}`, title: i === 0 ? ch.title : undefined, text: page.join('\n') });
    });
  return flat.map((p, i) => {
    const next = flat[i + 1];
    return {
      id: p.id,
      title: p.title,
      text: p.text,
      choices: [{ text: '다음', outcome: next ? { goto: next.id } : { do: [{ do: 'end', ending: 'record' }] } }],
    };
  });
}

