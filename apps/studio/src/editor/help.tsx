const GROUP_ORDER = ['시작하기', '이야기', '블록과 조건', '규칙', '결말', '설정', '도구', '중괄호 { } 문법', '용어 사전', '참고'];

/** 검색용 글자(JSX 안의 글까지) */
function plain(n: ReactNode): string {
  if (n == null || typeof n === 'boolean') return '';
  if (typeof n === 'string' || typeof n === 'number') return String(n);
  if (Array.isArray(n)) return n.map(plain).join(' ');
  if (typeof n === 'object' && 'props' in n) return plain((n.props as { children?: ReactNode }).children);
  return '';
}

function topicText(t: Topic): string {
  return [t.title, plain(t.summary), ...t.parts.map((p) => plain(Object.values(p) as ReactNode))].join(' ').toLowerCase();
}

export function HelpView({ topic }: { topic?: string }) {
  const { open } = useEditor();
  const [q, setQ] = useState('');
  const current = TOPICS.find((t) => t.id === topic) ?? TOPICS[0];
  const shown = q.trim() ? TOPICS.filter((t) => topicText(t).includes(q.trim().toLowerCase())) : TOPICS;
  const idx = TOPICS.indexOf(current);
  // 항목을 바꾸면 글 맨 위부터
  useEffect(() => {
    document.querySelector('.workspace')?.scrollTo(0, 0);
  }, [current]);

  return (
    <div className="help-view">
      <nav className="help-toc">
        <input className="search" placeholder="도움말 검색" value={q} onChange={(e) => setQ(e.target.value)} />
        {GROUP_ORDER.map((g) => {
          const list = shown.filter((t) => t.group === g);
          if (!list.length) return null;
          return (
            <div key={g} className="help-toc-group">
              <div className="help-toc-title">{g}</div>
              {list.map((t) => (
                <button key={t.id} type="button" className={t === current ? 'active' : ''} onClick={() => open('help', t.id)}>
                  {t.title}
                </button>
              ))}
            </div>
          );
        })}
        {shown.length === 0 && <p className="muted small">찾는 내용이 없습니다.</p>}
      </nav>

      <article className="help-article">
        <div className="help-crumb">{current.group}</div>
        <h2>{current.title}</h2>
        <p className="help-summary">{current.summary}</p>
        {current.screen && (
          <button type="button" className="btn small" onClick={() => open(current.screen!)}>
            이 화면 열기 →
          </button>
        )}
        {current.parts.map((p, i) => (
          <HelpPart key={i} part={p} />
        ))}
        <div className="help-pager">
          {idx > 0 && (
            <button type="button" className="link" onClick={() => open('help', TOPICS[idx - 1].id)}>
              ← {TOPICS[idx - 1].title}
            </button>
          )}
          <span className="spacer" />
          {idx < TOPICS.length - 1 && (
            <button type="button" className="link" onClick={() => open('help', TOPICS[idx + 1].id)}>
              {TOPICS[idx + 1].title} →
            </button>
          )}
        </div>
      </article>
    </div>
  );
}

function HelpPart({ part }: { part: Part }) {
  if ('what' in part)
    return (
      <section className="help-part">
        <h4>무엇인가요</h4>
        <p>{part.what}</p>
      </section>
    );
  if ('items' in part)
    return (
      <section className="help-part">
        {part.title && <h4>{part.title}</h4>}
        <dl className="help-items">
          {part.items.map(([term, desc], i) => (
            <div key={i} className="help-item">
              <dt>{term}</dt>
              <dd>{desc}</dd>
            </div>
          ))}
        </dl>
      </section>
    );
  if ('steps' in part)
    return (
      <section className="help-part">
        {part.title && <h4>{part.title}</h4>}
        <ol className="help-steps">
          {part.steps.map((s, i) => (
            <li key={i}>{s}</li>
          ))}
        </ol>
      </section>
    );
  if ('example' in part)
    return (
      <div className="help-callout is-example">
        <strong>{part.title ?? '예시'}</strong>
        <div>{part.example}</div>
      </div>
    );
  if ('note' in part)
    return (
      <div className="help-callout is-note">
        <strong>주의</strong>
        <div>{part.note}</div>
      </div>
    );
  return (
    <div className="help-callout is-tip">
      <strong>알아 두면 좋아요</strong>
      <div>{part.tip}</div>
    </div>
  );
}
